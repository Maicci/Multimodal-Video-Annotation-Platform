import { useEffect, useRef, useState } from "react";
import "../../assets/css/TranscriptViewer.css";

type Passage = { start_seconds: number; end_seconds: number; text: string };
type Job = {
  status: string;
  error: string | null;
  model: string;
  result: { language?: string; segments: Passage[] } | null;
};
type Props = {
  video: { id: string; filename: string };
  jobId: string;
  onClose: () => void;
};

const API_URL = import.meta.env.VITE_API_URL || "";

function timestamp(seconds: number) {
  const milliseconds = Math.round(Math.max(0, seconds) * 1000);
  const hours = Math.floor(milliseconds / 3600000);
  const minutes = Math.floor(milliseconds / 60000) % 60;
  const remainder = (milliseconds % 60000 / 1000).toFixed(3).padStart(6, "0");
  return `${hours ? `${hours}:` : ""}${String(minutes).padStart(2, "0")}:${remainder}`;
}

export default function TranscriptViewer({ video, jobId, onClose }: Props) {
  const dialogRef = useRef<HTMLDialogElement>(null);
  const playerRef = useRef<HTMLVideoElement>(null);
  const restorePlayback = useRef({ time: 0, playing: false });
  const [job, setJob] = useState<Job | null>(null);
  const [error, setError] = useState("");
  const [playbackError, setPlaybackError] = useState("");
  const [mediaToken, setMediaToken] = useState("");

  useEffect(() => {
    const dialog = dialogRef.current;
    dialog?.showModal();
    return () => dialog?.close();
  }, []);

  useEffect(() => {
    const controller = new AbortController();
    const headers = { Authorization: `Bearer ${localStorage.getItem("access_token")}` };
    fetch(`${API_URL}/api/processing/jobs/${jobId}`, { headers, signal: controller.signal })
      .then(async (response) => {
        if (!response.ok) throw new Error(response.status === 403
          ? "Only administrators can view automatic transcripts."
          : `Could not load transcript (${response.status}). Close this window and try again.`);
        const data: Job = await response.json();
        if (data.status !== "COMPLETED") throw new Error(data.error || "The transcript is not ready yet.");
        if (!data.result || !Array.isArray(data.result.segments)) throw new Error("No transcript result is available for this job.");
        return data;
      })
      .then((data) => { if (!controller.signal.aborted) setJob(data); })
      .catch((cause: unknown) => {
        if (!controller.signal.aborted) setError(cause instanceof Error ? cause.message : "Could not load transcript.");
      });

    async function refreshMediaToken() {
      try {
        const response = await fetch(`${API_URL}/api/videos/${video.id}/media-token`, {
          method: "POST", headers, signal: controller.signal,
        });
        if (!response.ok) throw new Error("Video preview is unavailable. Close this window and try again.");
        const data: { token: string } = await response.json();
        if (controller.signal.aborted) return;
        const player = playerRef.current;
        if (player && player.readyState >= 1) {
          restorePlayback.current = { time: player.currentTime, playing: !player.paused };
        }
        setMediaToken(data.token);
        setPlaybackError("");
      } catch (cause) {
        if (!controller.signal.aborted) setPlaybackError(cause instanceof Error ? cause.message : "Could not load preview.");
      }
    }
    void refreshMediaToken();
    const timer = window.setInterval(() => void refreshMediaToken(), 240000);
    return () => { controller.abort(); window.clearInterval(timer); };
  }, [jobId, video.id]);

  function playPassage(start: number) {
    const player = playerRef.current;
    if (!player) return;
    restorePlayback.current = { time: start, playing: true };
    if (player.readyState >= 1) {
      player.currentTime = start;
      void player.play().catch(() => setPlaybackError("Press Play in the video controls to start playback."));
    }
  }

  function closeDialog() {
    // Close before React removes the element so the browser restores focus.
    dialogRef.current?.close();
    onClose();
  }

  return (
    <dialog className="transcript-dialog" ref={dialogRef} aria-labelledby="transcript-title" onCancel={(event) => {
      event.preventDefault();
      closeDialog();
    }}>
      <header className="transcript-header">
        <div>
          <h2 id="transcript-title">Automatic transcript</h2>
          <p className="transcript-filename">{video.filename}</p>
        </div>
        <button type="button" onClick={closeDialog} aria-label="Close transcript">Close</button>
      </header>
      <p>Generated by Whisper. Click a timestamp to compare the text with the audio. This transcript is hidden from annotators.</p>
      <div className="transcript-layout">
        <div>
          <video ref={playerRef} controls preload="metadata" aria-label="Transcript video preview"
            src={mediaToken ? `${API_URL}/api/videos/${video.id}/stream?media_token=${encodeURIComponent(mediaToken)}` : undefined}
            onError={() => setPlaybackError("The video preview could not be played.")}
            onPlaying={() => setPlaybackError("")}
            onLoadedMetadata={() => {
              const player = playerRef.current;
              if (!player) return;
              player.currentTime = restorePlayback.current.time;
              if (restorePlayback.current.playing) void player.play().catch(() => {});
            }} />
          {playbackError && <p role="alert">{playbackError}</p>}
        </div>
        <div className="transcript-content" aria-busy={!job && !error}>
          {error && <p role="alert">{error}</p>}
          {!job && !error && <p role="status">Loading transcript…</p>}
          {job && <>
            <p>Model: {job.model}{job.result?.language ? ` · Language: ${job.result.language}` : ""}</p>
            {job.result?.segments.length === 0
              ? <p>No speech was recognized in this video. Play the audio to check whether speech is present.</p>
              : <ol className="transcript-passages" aria-label="Transcript passages">
                {job.result?.segments.map((passage, index) => (
                  <li key={index}>
                    <button type="button" disabled={!mediaToken} onClick={() => playPassage(passage.start_seconds)}
                      aria-label={`Play from ${timestamp(passage.start_seconds)}`}>
                      {timestamp(passage.start_seconds)} – {timestamp(passage.end_seconds)}
                    </button>
                    <p>{passage.text}</p>
                  </li>
                ))}
              </ol>}
          </>}
        </div>
      </div>
    </dialog>
  );
}
